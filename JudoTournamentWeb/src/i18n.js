const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const savedLocale = localStorage.getItem(STORAGE_KEY);
const locale = ref(
  languages.some((language) => language.code === savedLocale)
    ? savedLocale
    : DEFAULT_LOCALE,
);

const getMessage = (source, path) =>
  path.split(".").reduce((value, key) => value?.[key], source);
const hasCyrillic = (value) => /[А-Яа-яЁё]/.test(value);
const translateStatic = (value) => {
  const trimmed = value.trim();
  const translated = staticMessages[trimmed]?.[locale.value];

  if (!translated) return value;
  return value.replace(trimmed, translated);
};

const translateNode = (node) => {
  if (node.nodeType === Node.TEXT_NODE) {
    if (!originalText.has(node)) originalText.set(node, node.textContent);
    const source = originalText.get(node);
    if (hasCyrillic(source))
      node.textContent =
        locale.value === DEFAULT_LOCALE ? source : translateStatic(source);
    return;
  }

  if (node.nodeType !== Node.ELEMENT_NODE) return;
  if (["SCRIPT", "STYLE", "TEXTAREA"].includes(node.tagName)) return;

  const attributes = ["title", "alt", "placeholder", "aria-label"];
  attributes.forEach((attribute) => {
    if (!node.hasAttribute(attribute)) return;

    if (!originalAttributes.has(node)) originalAttributes.set(node, {});
    const originals = originalAttributes.get(node);
    if (!originals[attribute])
      originals[attribute] = node.getAttribute(attribute);

    const source = originals[attribute];
    if (hasCyrillic(source)) {
      node.setAttribute(
        attribute,
        locale.value === DEFAULT_LOCALE ? source : translateStatic(source),
      );
    }
  });

  node.childNodes.forEach(translateNode);
};

const translatePage = () => {
  if (typeof document === "undefined") return;
  translateNode(document.body);
};

export const setLocale = (nextLocale) => {
  if (!languages.some((language) => language.code === nextLocale)) return;

  locale.value = nextLocale;
  localStorage.setItem(STORAGE_KEY, nextLocale);
  document.documentElement.lang = nextLocale;
  setTimeout(translatePage);
};

export const t = (key, params = {}) => {
  const template =
    getMessage(messages[locale.value], key) ??
    getMessage(messages[DEFAULT_LOCALE], key) ??
    key;

  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, value),
    template,
  );
};

export const useI18n = () => ({
  locale,
  languages,
  currentLanguage: computed(
    () =>
      languages.find((language) => language.code === locale.value) ??
      languages[0],
  ),
  setLocale,
  t,
});

export const installI18n = (app) => {
  document.documentElement.lang = locale.value;
  app.config.globalProperties.$t = t;
  app.mixin({
    mounted() {
      setTimeout(translatePage);
    },
    updated() {
      setTimeout(translatePage);
    },
  });
};
